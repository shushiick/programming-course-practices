#!/bin/bash
# --- Раздел 8. Обработка ошибок
# --- Запуск: sudo ./8_error_handling.sh

# --- Выход при ошибке
set -e

# --- Проверка прав администратора
if [ "$EUID" -ne 0 ]; then
    echo "Для выполнения скрипта требуются права root"
    exit 1
fi

# --- Логирование ошибок
exec 2> error.log

# --- Папка для копии (в методичке не создавалась, без неё cp не работает)
mkdir -p backup

# --- Пример с обработкой ошибок команды
cp important_file.txt backup/ || {
    echo "Ошибка копирования файла"
    exit 1
}

echo "Файл скопирован"

#!/bin/bash
# --- Раздел 7. Простой сканер портов
# --- Сканирую только свой компьютер (127.0.0.1), а не 192.168.1.1 из методички.
# --- Добавлен вывод закрытых портов, чтобы было видно, что проверка прошла.

TARGET="127.0.0.1"

echo "Сканирование портов на $TARGET"
for port in 22 80 443 8080; do
    nc -z -w 1 $TARGET $port 2>/dev/null
    if [ $? -eq 0 ]; then
        echo "Порт $port открыт"
    else
        echo "Порт $port закрыт"
    fi
done

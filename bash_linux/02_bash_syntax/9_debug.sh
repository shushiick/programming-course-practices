#!/bin/bash
# --- Раздел 9. Отладка скриптов

# --- Включение отладки
set -x  # --- Показывает выполняемые команды
set -e  # --- Выход при первой ошибке
set -u  # --- Выход при использовании необъявленных переменных

NAME="debug"
for i in 1 2 3; do
    echo "Шаг $i для $NAME"
done

# --- Выключение отладки
set +x
echo "Отладка выключена"

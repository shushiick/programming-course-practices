#!/bin/bash
# --- Раздел 7. Мониторинг ресурсов системы
# --- Загрузка CPU берётся после слов «load average:», потому что номер
# --- столбца в выводе uptime зависит от того, сколько работает система.

echo "--- Мониторинг системы"
echo "Дата: $(date)"
echo "Загрузка CPU:$(uptime | awk -F'load average:' '{print $2}')"
echo "Свободная память: $(free -h | grep Mem | awk '{print $4}')"
echo "Дисковое пространство:"
df -h / | tail -1

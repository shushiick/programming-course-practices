#!/bin/bash
# --- Счётчик с разными способами увеличения

count=0

#  Способ 1: через $(( ))
count=$((count + 1))
echo "После первого увеличения: $count"

# Способ 2: сокращённая запись (( count++ ))
(( count++ ))
echo "После второго увеличения: $count"

# Способ 3: прибавить сразу 5
(( count += 5 ))
echo "После += 5: $count"

# Способ 4: умножить
(( count *= 2 ))
echo "После *= 2: $count"

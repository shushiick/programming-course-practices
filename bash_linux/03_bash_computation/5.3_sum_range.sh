#!/bin/bash
# --- Сумма чисел от 1 до N
# --- Задание 7: дополнительно произведение (факториал)
read -p "Введите N: " n

sum=0
prod=1
i=1

while [ "$i" -le "$n" ]; do
    sum=$((sum + i))
    prod=$((prod * i))
    i=$((i + 1))
done

echo "Сумма чисел от 1 до $n = $sum"
echo "Произведение чисел от 1 до $n ($n!) = $prod"
